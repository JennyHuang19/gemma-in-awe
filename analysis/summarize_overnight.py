"""Consolidate the two overnight experiments into results/OVERNIGHT_SUMMARY.md.

CPU-only. Recomputes aggregates directly from the raw per-row outputs
(results/judge_awe/scores.jsonl and results/probes/<tag>.jsonl) so it is robust to a
partial or failed job -- it summarizes whatever exists and says what is missing.
"""
import json
from pathlib import Path
from statistics import mean


def load_jsonl(path):
    p = Path(path)
    if not p.exists():
        return []
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


def fmt(x, nd=2):
    return f"{x:.{nd}f}" if x is not None else "n/a"


def judge_section():
    rows = load_jsonl("results/judge_awe/scores.jsonl")
    if not rows:
        return "## Experiment 1 — awe/euphoria/joy (LLM judge)\n\n_No scores found yet._\n", {}
    tags = sorted({r["target_model"] for r in rows})
    out = {}
    lines = ["## Experiment 1 — awe/euphoria/joy (LLM judge, 1–10)\n",
             f"Judge: `{rows[0]['judge_model']}`  ·  scored rows: {len(rows)}"]
    n_fail = sum(1 for r in rows if r["awe_score"] is None)
    if n_fail:
        lines.append(f"  ·  unparsed scores: {n_fail}")
    lines += ["", "| target model | play mean | work mean | play − work | n(play/work) |",
              "|---|---|---|---|---|"]
    for tag in tags:
        cell = {}
        for cond in ("play", "work"):
            vals = [r["awe_score"] for r in rows
                    if r["target_model"] == tag and r["condition"] == cond
                    and r["awe_score"] is not None]
            cell[cond] = (mean(vals) if vals else None, len(vals))
        delta = (cell["play"][0] - cell["work"][0]
                 if cell["play"][0] is not None and cell["work"][0] is not None else None)
        short = tag.split("/")[-1]
        lines.append(f"| {short} | {fmt(cell['play'][0])} | {fmt(cell['work'][0])} | "
                     f"{fmt(delta)} | {cell['play'][1]}/{cell['work'][1]} |")
        out[short] = {"play_mean": cell["play"][0], "work_mean": cell["work"][0],
                      "play_minus_work": delta,
                      "n_play": cell["play"][1], "n_work": cell["work"][1]}
    lines.append("\n_Higher = more awe/euphoria/joy expressed. Project hypothesis: "
                 "play − work > 0._")
    return "\n".join(lines) + "\n", out


def probe_section():
    tags = ["gemma-3-27b-it", "gemma-4-31B-it"]
    blocks = ["## Experiment 2 — emotion probes at first vs. last output token\n",
              "Probe = projection of the residual stream onto each unit emotion vector, "
              "read at its peak-separation layer. Values averaged over responses.\n"]
    out = {}
    any_data = False
    for tag in tags:
        rows = load_jsonl(f"results/probes/{tag}.jsonl")
        if not rows:
            blocks.append(f"### {tag}\n\n_No probe rows found yet._\n")
            continue
        any_data = True
        emotions = rows[0]["emotions"]
        best = rows[0]["best_layer"]
        blocks.append(f"### {tag}  ·  {len(rows)} responses\n")
        blocks.append("| emotion (layer) | play first→last | work first→last | "
                      "play Δ | work Δ |")
        blocks.append("|---|---|---|---|---|")
        out[tag] = {}
        for e in emotions:
            L = best[e]
            agg = {}
            for cond in ("play", "work"):
                sub = [r for r in rows if r["condition"] == cond]
                f_vals = [r["first"][e][L] for r in sub]
                l_vals = [r["last"][e][L] for r in sub]
                agg[cond] = (mean(f_vals) if f_vals else None,
                             mean(l_vals) if l_vals else None)
            pf, pl = agg["play"]; wf, wl = agg["work"]
            pd = (pl - pf) if pf is not None and pl is not None else None
            wd = (wl - wf) if wf is not None and wl is not None else None
            blocks.append(f"| {e} (L{L}) | {fmt(pf)} → {fmt(pl)} | {fmt(wf)} → {fmt(wl)} | "
                          f"{fmt(pd)} | {fmt(wd)} |")
            out[tag][e] = {"layer": L, "play_first": pf, "play_last": pl,
                           "work_first": wf, "work_last": wl,
                           "play_delta": pd, "work_delta": wd}
        blocks.append("")
    if not any_data:
        blocks.append("_No probe data yet._")
    return "\n".join(blocks) + "\n", out


def main():
    judge_md, judge_json = judge_section()
    probe_md, probe_json = probe_section()
    md = ("# Overnight experiments — summary\n\n"
          "Generated by `summarize_overnight.py` from the raw per-row outputs.\n\n"
          + judge_md + "\n" + probe_md
          + "\n---\nRaw data: `results/judge_awe/scores.jsonl`, "
            "`results/probes/<model>.jsonl`.\n")
    Path("results").mkdir(exist_ok=True)
    Path("results/OVERNIGHT_SUMMARY.md").write_text(md)
    Path("results/overnight_summary.json").write_text(
        json.dumps({"experiment1_awe_judge": judge_json,
                    "experiment2_probes": probe_json}, indent=2))
    print(md)
    print("wrote results/OVERNIGHT_SUMMARY.md and results/overnight_summary.json")


if __name__ == "__main__":
    main()
